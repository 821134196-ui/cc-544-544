def _png_chunk(kind: bytes, data: bytes) -> bytes:
    return (
        struct.pack(">I", len(data))
        + kind
        + data
        + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
    )


def _write_png(path: Path, width: int, height: int, pixels: bytearray) -> None:
    raw = bytearray()
    for y in range(height):
        raw.append(0)  # filter type 0
        raw.extend(pixels[y * width * 3 : (y + 1) * width * 3])
    png = b"\x89PNG\r\n\x1a\n"
    png += _png_chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
    png += _png_chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    png += _png_chunk(b"IEND", b"")
    path.write_bytes(png)


def _put_pixel(buf: bytearray, w: int, x: int, y: int, rgb: tuple[int, int, int]) -> None:
    if 0 <= x < w and 0 <= y < len(buf) // (w * 3):
        i = (y * w + x) * 3
        buf[i : i + 3] = bytes(rgb)


def _rect(
    buf: bytearray, w: int, h: int, x0: int, y0: int, x1: int, y1: int,
    rgb: tuple[int, int, int], fill: bool = True,
) -> None:
    for y in range(max(0, y0), min(h, y1 + 1)):
        for x in range(max(0, x0), min(w, x1 + 1)):
            if fill or x in (x0, x1) or y in (y0, y1):
                _put_pixel(buf, w, x, y, rgb)


def _draw_text(
    buf: bytearray, w: int, text: str, x: int, y: int,
    rgb: tuple[int, int, int], scale: int = 2,
) -> None:
    h = len(buf) // (w * 3)
    cx = x
    for ch in text.upper():
        glyph = _FONT.get(ch, ["11111"] * 7)
        for gy, row in enumerate(glyph):
            for gx, bit in enumerate(row):
                if bit == "1":
                    _rect(buf, w, h, cx + gx * scale, y + gy * scale,
                          cx + gx * scale + scale - 1, y + gy * scale + scale - 1, rgb)
        cx += 6 * scale


def make_photo(
    photos_dir: str | Path,
    label: str,
    base_rgb: tuple[int, int, int],
    size: tuple[int, int] = (360, 240),
) -> str:
    """生成虚构照片，返回文件名（相对 photos 目录）。

    label 会烧录在图片上；base_rgb 决定主色调，不同结论可用不同色块直观区分。
    """
    photos_dir = Path(photos_dir)
    photos_dir.mkdir(parents=True, exist_ok=True)
    w, h = size
    digest = hashlib.sha256(f"{label}|{base_rgb}|{w}x{h}".encode()).hexdigest()[:10]
    name = f"photo_{digest}.png"
    path = photos_dir / name
    if path.exists():
        return name

    pixels = bytearray(b"\xff" * (w * h * 3))  # 白底
    # 主色块（物品轮廓占位）
    _rect(pixels, w, h, 30, 46, w - 30, h - 40, base_rgb)
    # 深灰描边
    edge = (45, 45, 45)
    _rect(pixels, w, h, 30, 46, w - 30, h - 40, edge, fill=False)
    # 标签条（深灰底白字）
    _rect(pixels, w, h, 0, 0, w - 1, 28, (235, 235, 235))
    _draw_text(pixels, w, label[:28], 8, 5, edge, scale=2)
    # 角落十字准星，暗示「现场拍摄」
    for cx, cy in ((44, 60), (w - 44, 60), (44, h - 54), (w - 44, h - 54)):
        _rect(pixels, w, h, cx - 6, cy, cx + 6, cy, edge)
        _rect(pixels, w, h, cx, cy - 6, cx, cy + 6, edge)
    _write_png(path, w, h, pixels)
    return name
